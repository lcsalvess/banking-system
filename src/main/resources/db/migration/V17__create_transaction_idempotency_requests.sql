CREATE TABLE transaction_idempotency_requests
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id          BIGINT                      NOT NULL,
    idempotency_key  UUID                        NOT NULL,
    operation_type   VARCHAR(20)                 NOT NULL,
    request_hash     CHAR(64)                    NOT NULL,
    transaction_code UUID,

    created_at       TIMESTAMP WITHOUT TIME ZONE NOT NULL
        DEFAULT (
            CURRENT_TIMESTAMP AT TIME ZONE 'America/Sao_Paulo'
            ),

    CONSTRAINT fk_transaction_idempotency_user
        FOREIGN KEY (user_id)
            REFERENCES users (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_transaction_idempotency_transaction
        FOREIGN KEY (transaction_code)
            REFERENCES transactions (transaction_code)
            ON DELETE RESTRICT,

    CONSTRAINT uk_transaction_idempotency_user_key
        UNIQUE (user_id, idempotency_key),

    CONSTRAINT uk_transaction_idempotency_transaction_code
        UNIQUE (transaction_code),

    CONSTRAINT ck_transaction_idempotency_operation
        CHECK (
            operation_type IN (
                               'DEPOSIT',
                               'WITHDRAWAL',
                               'TRANSFER'
                )
            ),

    CONSTRAINT ck_transaction_idempotency_request_hash
        CHECK (request_hash ~ '^[0-9a-f]{64}$')
);