-- Append-only audit trail for security- and money-relevant operations.
-- Rows are written in the same database transaction as the audited change and
-- can never be updated, deleted or truncated.
-- There is deliberately no foreign key to users: the trail must outlive (and
-- never block) changes to the audited data, so the actor is kept as a snapshot.

CREATE TABLE audit_events
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    event_type     VARCHAR(50)                 NOT NULL,
    outcome        VARCHAR(20)                 NOT NULL,

    actor_type     VARCHAR(20)                 NOT NULL,
    actor_user_id  BIGINT,
    actor_username VARCHAR(20),

    entity_type    VARCHAR(30)                 NOT NULL,
    entity_id      VARCHAR(64)                 NOT NULL,

    correlation_id UUID,

    created_at     TIMESTAMP WITHOUT TIME ZONE NOT NULL
        DEFAULT (
            CURRENT_TIMESTAMP AT TIME ZONE 'America/Sao_Paulo'
            ),

    CONSTRAINT ck_audit_events_event_type
        CHECK (event_type ~ '^[A-Z][A-Z_]*$'),

    CONSTRAINT ck_audit_events_outcome
        CHECK (outcome IN ('SUCCESS', 'FAILURE', 'DENIED')),

    CONSTRAINT ck_audit_events_entity_type
        CHECK (entity_type ~ '^[A-Z][A-Z_]*$'),

    CONSTRAINT ck_audit_events_entity_id
        CHECK (length(entity_id) > 0),

    CONSTRAINT ck_audit_events_actor
        CHECK (
            (actor_type = 'USER'
                AND actor_user_id IS NOT NULL
                AND actor_username IS NOT NULL)
                OR (actor_type = 'SYSTEM'
                AND actor_user_id IS NULL
                AND actor_username IS NULL)
                OR (actor_type = 'ANONYMOUS'
                AND actor_user_id IS NULL)
            )
);

CREATE INDEX idx_audit_events_entity
    ON audit_events (entity_type, entity_id, id DESC);

CREATE INDEX idx_audit_events_actor
    ON audit_events (actor_user_id, id DESC)
    WHERE actor_user_id IS NOT NULL;

-- Enforce append-only at the database level.
CREATE FUNCTION audit_events_reject_change()
    RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'audit_events is append-only: % is not allowed', TG_OP
        USING ERRCODE = 'restrict_violation';
END
$$;

CREATE TRIGGER trg_audit_events_no_update_delete
    BEFORE UPDATE OR DELETE
    ON audit_events
    FOR EACH ROW
EXECUTE FUNCTION audit_events_reject_change();

CREATE TRIGGER trg_audit_events_no_truncate
    BEFORE TRUNCATE
    ON audit_events
    FOR EACH STATEMENT
EXECUTE FUNCTION audit_events_reject_change();
